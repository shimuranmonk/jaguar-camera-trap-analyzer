CREDIT='generated by Alapaap.net - open mind open skies'
MAX_ROWS=1_048_576
MAX_TEXT=32_767


def safe(value):
    if isinstance(value,(dict,list,tuple)):
        value=json.dumps(value,ensure_ascii=False,sort_keys=True)
    if isinstance(value,str):
        if len(value)>MAX_TEXT:
            raise ValueError('A cell exceeds the XLSX text limit; raw content must use chunk rows.')
        if value.startswith(('=','+','-','@','\t','\r','\n')):
            value="'"+value
        if len(value)>MAX_TEXT:
            raise ValueError('A protected cell exceeds the XLSX text limit.')
        value=''.join(character for character in value if character in '\t\n\r' or ord(character)>=32)
    return value


def chunks(value):
    text=value if isinstance(value,str) else json.dumps(value,ensure_ascii=False,sort_keys=True)
    for index in range(0,max(1,len(text)),30_000):
        yield index//30_000+1,text[index:index+30_000]


class Sheets:
    def __init__(self,workbook):
        self.workbook=workbook
        self.counts={}
        self.dictionary=[]

    def write(self,title,headers,rows,grain):
        self.dictionary.extend((title,column,grain,column.replace('_',' ').capitalize()+'. Source-specific values retain their provenance.',
            'Fahrenheit' if column=='ocr_temperature_f' else ('Original ExifTool tag units/codes' if column.startswith('exif_raw.') else 'Confidence 0-1; temperature C unless explicitly named F; GPS degrees; detection coordinates normalized xywh.'),
            'Blank means unavailable or not applicable.') for column in headers)
        sheet=None
        part=0
        row_number=MAX_ROWS
        count=0
        for row in rows:
            if row_number>=MAX_ROWS:
                if sheet:
                    sheet.auto_filter.ref=f'A1:{self.column(len(headers))}{row_number}'
                part+=1
                sheet=self.workbook.create_sheet(title if part==1 else title[:26]+' '+str(part))
                sheet.freeze_panes='A2'
                for index in range(1,len(headers)+1):
                    sheet.column_dimensions[self.column(index)].width=min(44,max(16,len(headers[index-1])+2))
                cells=[]
                for text in headers:
                    cell=WriteOnlyCell(sheet,text)
                    cell.font=Font(bold=True,color='FFFFFF')
                    cell.fill=PatternFill('solid',fgColor='365F68')
                    cells.append(cell)
                sheet.append(cells)
                row_number=1
            cells=[]
            for column,value in zip(headers,row):
                if column in {'raw_json','payload_json','config_json'} and isinstance(value,str):
                    if len(value)>MAX_TEXT:
                        raise ValueError('A JSON chunk exceeds the XLSX text limit.')
                    # Explicit string cells preserve chunk boundaries without
                    # turning leading =/+/- text into formulas or adding bytes.
                    cell=WriteOnlyCell(sheet,value)
                    cell.data_type='s'
                    cells.append(cell)
                else:
                    cells.append(safe(value))
            sheet.append(cells)
            row_number+=1
            count+=1
        if sheet is None:
            sheet=self.workbook.create_sheet(title)
            sheet.freeze_panes='A2'
            cells=[]
            for text in headers:
                cell=WriteOnlyCell(sheet,text)
                cell.font=Font(bold=True,color='FFFFFF')
                cell.fill=PatternFill('solid',fgColor='365F68')
                cells.append(cell)
            sheet.append(cells)
            row_number=1
        sheet.auto_filter.ref=f'A1:{self.column(len(headers))}{row_number}'
        self.counts[title]=count

    @staticmethod
    def column(number):
        from openpyxl.utils import get_column_letter
        return get_column_letter(number)


def export_workbook(database,destination,scope=None,progress=lambda value:None):
    database,destination=Path(database).resolve(),Path(destination).resolve()
    if destination.suffix.lower()!='.xlsx':
        raise ValueError('The output file must use the .xlsx extension.')
    scope=dict(scope or {})
    for name in ['start_date','end_date']:
        if scope.get(name):
            date.fromisoformat(scope[name])
    if scope.get('start_date') and scope.get('end_date') and scope['start_date']>scope['end_date']:
        raise ValueError('End date must follow start date.')
    reserved=False
    temporary=None
    with import_lock(database):
        project=open_project(database)
        try:
            with destination.open('xb'):
                pass
            reserved=True
            with tempfile.NamedTemporaryFile(suffix='.xlsx',prefix='.jaguar-',dir=destination.parent,delete=False) as handle:
                temporary=Path(handle.name)
            with closing(sqlite3.connect(database)) as connection:
                connection.execute('PRAGMA foreign_keys=ON')
                connection.execute('BEGIN')
                clauses=['1=1']
                parameters={}
                if scope.get('image_ids') is not None:
                    clauses.append('i.id IN (SELECT value FROM json_each(:ids))')
                    parameters['ids']=json.dumps(scope['image_ids'])
                if scope.get('run_id'):
                    clauses.append('EXISTS(SELECT 1 FROM processing_records WHERE image_id=i.id AND run_id=:run)')
                    parameters['run']=scope['run_id']
                if scope.get('camera_id'):
                    clauses.append('(SELECT camera_id FROM image_assignments a WHERE a.image_id=i.id ORDER BY rowid DESC LIMIT 1) IS NULL' if scope['camera_id']=='unassigned' else '(SELECT camera_id FROM image_assignments a WHERE a.image_id=i.id ORDER BY rowid DESC LIMIT 1)=:camera')
                    parameters['camera']=scope['camera_id']
                for name,operator in [('start_date','>='),('end_date','<=')]:
                    if scope.get(name):
                        clauses.append("(SELECT substr(json_extract(value_json,'$.iso8601'),1,10) FROM metadata_resolved WHERE image_id=i.id AND field='capture_timestamp')"+operator+':'+name)
                        parameters[name]=scope[name]
                connection.execute('CREATE TEMP TABLE export_scope AS SELECT i.id FROM images i WHERE '+' AND '.join(clauses),parameters)
                selected=connection.execute('SELECT count(*) FROM export_scope').fetchone()[0]
                workbook=Workbook(write_only=True)
                workbook.create_sheet('README')
                sheets=Sheets(workbook)
                def query(sql,args=()):
                    return connection.execute(sql,args)
                write_analysis(connection,sheets)
                write_species(connection,sheets,chunks)
                def values(image_id):
                    return {field:(json.loads(value),source,conflict) for field,value,source,conflict in query('SELECT field,value_json,source,conflict FROM metadata_resolved WHERE image_id=?',(image_id,))}
                def image_rows():
                    for identity,sha in query('SELECT i.id,i.sha256 FROM images i JOIN export_scope s ON s.id=i.id ORDER BY i.id'):
                        metadata=values(identity)
                        get=lambda field:metadata.get(field,(None,None,0))[0]
                        path=query('SELECT absolute_path FROM image_paths WHERE image_id=? ORDER BY is_available DESC,absolute_path LIMIT 1',(identity,)).fetchone()
                        assignment=query('SELECT camera_id,deployment_id FROM image_assignments WHERE image_id=? ORDER BY rowid DESC LIMIT 1',(identity,)).fetchone() or (None,None)
                        det=query("SELECT r.id,r.payload_json FROM processing_records r JOIN processing_runs p ON p.id=r.run_id WHERE image_id=? AND p.stage='detect' AND r.status='succeeded' ORDER BY r.rowid DESC LIMIT 1",(identity,)).fetchone()
                        detection=json.loads(det[1]) if det else None
                        classes={box['class'] for box in detection['detections']} if detection else set()
                        timestamp=get('capture_timestamp')
                        yield (identity,Path(path[0]).name if path else None,path[0] if path else None,sha,*assignment,get('make'),get('model'),get('physical_camera_id'),get('site_label'),timestamp.get('iso8601') if timestamp else None,timestamp.get('timezone_known') if timestamp else None,get('temperature_c'),get('latitude'),get('longitude'),get('width'),get('height'),any(v[2] for v in metadata.values()),query("SELECT count(*) FROM reviews WHERE image_id=? AND status='open'",(identity,)).fetchone()[0],*('animal' in classes,'person' in classes,'vehicle' in classes),detection['outcome'] if detection else 'not_processed')
                sheets.write('Images',['image_id','filename','primary_source_path','sha256','camera_id','deployment_id','make','model','physical_camera_serial','camera_site_label','capture_timestamp','timezone_known','temperature_c','latitude','longitude','width','height','has_conflict','open_review_cases','animal','person','vehicle','detection_outcome'],image_rows(),'One row per logical image')
                sheets.write('Image Paths',['path_id','image_id','source_root_id','absolute_path','relative_path','file_size','mtime_ns','is_available'],query('SELECT p.* FROM image_paths p JOIN export_scope s ON s.id=p.image_id ORDER BY image_id,absolute_path'),'One row per retained file path')
                sheets.write('Cameras',['camera_id','make','model','serial','label','created_at','deployment_id','site_label','start_at','end_at','notes'],query('SELECT c.*,d.id,d.site_label,d.start_at,d.end_at,d.notes FROM cameras c LEFT JOIN deployments d ON d.camera_id=c.id WHERE c.id IN (SELECT a.camera_id FROM image_assignments a JOIN export_scope s ON s.id=a.image_id) ORDER BY c.id,d.id'),'One row per assigned physical camera and deployment combination')
                sheets.write('Detections',['detection_id','source_record_id','image_id','run_id','class','confidence','x','y','width','height','model_version','threshold'],query('SELECT d.* FROM detections d JOIN export_scope s ON s.id=d.image_id ORDER BY image_id,run_id,d.id'),'One row per stored accepted bounding box; historical runs retained')
                def raw_exif():
                    for record_id,run_id,image_id,raw,version in query('SELECT e.id,e.run_id,e.image_id,e.raw_json,x.tool_version FROM exif_records e JOIN exif_runs x ON x.id=e.run_id JOIN export_scope s ON s.id=e.image_id ORDER BY image_id,e.rowid'):
                        if raw is None:
                            continue
                        for part,text in chunks(raw):
                            yield record_id,run_id,image_id,version,part,text
                sheets.write('EXIF Metadata',['record_id','run_id','image_id','tool_version','part','raw_json'],raw_exif(),'One row per EXIF JSON record chunk; ordered parts reconstruct exact output')
                def raw_ocr():
                    for record_id,run_id,image_id,payload in query("SELECT r.id,r.run_id,r.image_id,r.payload_json FROM processing_records r JOIN processing_runs p ON p.id=r.run_id JOIN export_scope s ON s.id=r.image_id WHERE p.stage='ocr' ORDER BY r.image_id,r.rowid"):
                        if not payload:
                            continue
                        data=json.loads(payload)
                        for index,token in enumerate(data['tokens']):
                            for part,text in chunks(token['text']):
                                yield record_id,run_id,image_id,data['profile']['id'],data['profile']['version'],index,part,text,token['confidence'],token['region'],token['polygon']
                sheets.write('OCR Metadata',['record_id','run_id','image_id','profile_id','profile_version','token_index','part','raw_text','confidence','region','polygon'],raw_ocr(),'One row per OCR token text chunk; historical runs retained')
                sheets.write('Observations',['observation_id','image_id','field','source','value_json','raw_json','confidence','source_record_id','observed_at'],((identity,image,field,source,value,raw if len(raw or '')<=MAX_TEXT else 'See source record '+record,confidence,record,at) for identity,image,field,source,value,raw,confidence,record,at in query('SELECT m.* FROM metadata_observations m JOIN export_scope s ON s.id=m.image_id ORDER BY image_id,field,observed_at,id')),'One row per immutable metadata observation; large raw OCR content references source record')
                sheets.write('Metadata Conflicts',['image_id','field','selected_value','selected_source','provenance','conflict','updated_at'],query('SELECT m.* FROM metadata_resolved m JOIN export_scope s ON s.id=m.image_id WHERE conflict=1 ORDER BY image_id,field'),'One row per currently conflicting field; source candidates join through Observations')
                sheets.write('Reviews',['review_id','image_id','reason','fingerprint','detail','status','created_at','resolved_at'],query('SELECT r.* FROM reviews r JOIN export_scope s ON s.id=r.image_id ORDER BY image_id,created_at,r.id'),'One row per review case, including historical/superseded cases')
                sheets.write('Audit',['event_id','image_id','field','old_value','new_value','actor','reason','action','timestamp'],query('SELECT a.* FROM audit_events a JOIN export_scope s ON s.id=a.image_id ORDER BY at,a.id'),'One row per human audit event')
                errors=[]
                for image_id,path,run_id,error,at in query("SELECT e.image_id,e.source_path,e.run_id,e.error,e.extracted_at FROM exif_records e JOIN export_scope s ON s.id=e.image_id WHERE status='failed'"):
                    errors.append((image_id,path,run_id,'exif','extraction_failed',error,at))
                for image_id,run_id,stage,error,at in query("SELECT r.image_id,r.run_id,p.stage,r.error,r.processed_at FROM processing_records r JOIN processing_runs p ON p.id=r.run_id JOIN export_scope s ON s.id=r.image_id WHERE r.status='failed'"):
                    errors.append((image_id,None,run_id,stage,'processing_failed',error,at))
                if scope.get('image_ids') is None and not any(scope.get(key) for key in ['run_id','camera_id','start_date','end_date']):
                    for image_id,path,run_id,error,at in query("SELECT t.image_id,t.absolute_path,t.run_id,t.error,r.started_at FROM import_items t JOIN import_runs r ON r.id=t.run_id WHERE t.status='failed'"):
                        errors.append((image_id,path,run_id,'import','import_failed',error,at))
                sheets.write('Errors',['image_id','source_path','run_id','stage','error_code','message','timestamp'],errors,'One row per failure; unfiltered exports also include imports without logical image IDs')
                configs=[]
                runs=[]
                for identity,status,started,ended,roots in query('SELECT id,status,started_at,ended_at,roots_json FROM import_runs ORDER BY rowid'):
                    runs.append((identity,'import',status,started,ended,None,identity))
                    configs.extend((identity,part,text) for part,text in chunks(roots))
                for identity,status,version,started,ended in query('SELECT id,status,tool_version,started_at,ended_at FROM exif_runs ORDER BY rowid'):
                    runs.append((identity,'exif',status,started,ended,version,'Not applicable'))
                for identity,stage,status,started,ended,config in query('SELECT id,stage,status,started_at,ended_at,config_json FROM processing_runs ORDER BY rowid'):
                    runs.append((identity,stage,status,started,ended,None,identity))
                    configs.extend((identity,part,text) for part,text in chunks(config))
                sheets.write('Runs',['run_id','stage','status','started_at','ended_at','tool_version','config_reference'],runs,'One row per project processing run; image-level sheets define scoped membership')
                sheets.write('Run Config',['run_id','part','config_json'],configs,'One row per configuration JSON chunk')
                export_id,created=str(uuid4()),now()
                schema=query('SELECT max(version) FROM schema_migrations').fetchone()[0]
                sheets.write('Export Info',['export_id','created_at','app_version','schema_version','selected_images','scope_json','units','credit'],[(export_id,created,__version__,schema,selected,json.dumps(scope) if len(json.dumps(scope))<=MAX_TEXT else 'Scope is recorded in the local exports table.','Temperatures C; confidence 0-1; detection coordinates normalized xywh',CREDIT)],'One row per current export')
                dictionary=workbook['README']
                dictionary.freeze_panes='A2'
                dictionary.append(['sheet','column','row_grain','description','units','null_rules'])
                dictionary.append(['Document','credit',CREDIT,'','',''])
                for row in sheets.dictionary:
                    dictionary.append([safe(value) for value in row])
                dictionary.auto_filter.ref=f'A1:F{len(sheets.dictionary)+2}'
                workbook.save(temporary)
                with temporary.open('rb') as handle:
                    digest=hashlib.file_digest(handle,'sha256').hexdigest()
                os.replace(temporary,destination)
                temporary=None
                with connection:
                    connection.execute('INSERT INTO exports VALUES (?,?,?,?,?,?,?,?)',(export_id,project.id,str(destination),created,json.dumps(scope),json.dumps(sheets.counts),digest,__version__))
                progress({'status':'completed','path':str(destination),'images':selected})
                return {'path':str(destination),'images':selected,'counts':sheets.counts,'sha256':digest}
        except Exception:
            if temporary:
                temporary.unlink(missing_ok=True)
            if reserved:
                destination.unlink(missing_ok=True)
            raise
