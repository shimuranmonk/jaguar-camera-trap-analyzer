"""Synthetic import/recovery load check; never substitutes for field acceptance."""
import argparse
import hashlib
import json
import multiprocessing
import shutil
import sqlite3
import time
from pathlib import Path

from PySide6.QtGui import QImage,QColor
from jaguar.db.projects import create_project
from jaguar.ingest.service import import_folders,latest_summary


def interrupted_import(database,source,channel):
    def progress(value):
        if value['imported']>=1000:
            try:
                import psutil
                memory=psutil.Process().memory_info().rss
            except ImportError:
                memory=None
            channel.send((value,memory))
            channel.recv()
    import_folders(database,[source],progress=progress)


def identity(path):
    with path.open('rb') as handle:
        return hashlib.file_digest(handle,'sha256').hexdigest(),path.stat().st_mtime_ns


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--directory',required=True)
    parser.add_argument('--report',required=True)
    args=parser.parse_args()
    root=Path(args.directory).resolve()
    root.mkdir(parents=True,exist_ok=False)
    source=root/'sources'
    source.mkdir()
    started=time.perf_counter()
    for index in range(5100):
        folder=source/f'batch-{index//500:02d}'
        folder.mkdir(exist_ok=True)
        image=QImage(24,24,QImage.Format.Format_RGB32)
        image.fill(QColor.fromRgb(0xff000000|index))
        if not image.save(str(folder/f'image-{index:05d}.PNG'),'PNG'):
            raise RuntimeError('Synthetic fixture could not be written.')
    for index in range(100):
        shutil.copy2(source/'batch-00'/f'image-{index:05d}.PNG',source/f'duplicate-{index:03d}.PNG')
    for index in range(5):
        (source/f'corrupt-{index}.JPG').write_bytes(b'not a valid image')
    before={str(path.relative_to(source)):identity(path) for path in source.rglob('*') if path.is_file()}
    generation=time.perf_counter()-started
    database=root/'load.sqlite'
    create_project(database,'Synthetic import recovery check')
    context=multiprocessing.get_context('spawn')
    parent,child=context.Pipe()
    worker=context.Process(target=interrupted_import,args=(str(database),str(source),child))
    started=time.perf_counter()
    worker.start()
    if not parent.poll(300):
        worker.terminate()
        worker.join(10)
        raise RuntimeError('The worker did not reach its checkpoint in five minutes.')
    checkpoint,child_memory=parent.recv()
    worker.terminate()
    worker.join(10)
    worker.close()
    parent.close()
    child.close()
    interrupted_elapsed=time.perf_counter()-started
    previous=latest_summary(database)
    observed_memory=[child_memory or 0]
    def progress(value):
        try:
            import psutil
            observed_memory.append(psutil.Process().memory_info().rss)
        except ImportError:
            pass
    started=time.perf_counter()
    result=import_folders(database,[source],progress=progress)
    resumed_elapsed=time.perf_counter()-started
    assert result['run_id']==previous['run_id']
    assert (result['discovered'],result['imported'],result['unique_images'],result['duplicates'],result['failed'])==(5205,5200,5100,100,5),result
    assert before=={str(path.relative_to(source)):identity(path) for path in source.rglob('*') if path.is_file()}
    with sqlite3.connect(database) as connection:
        assert connection.execute('SELECT count(*) FROM images').fetchone()[0]==5100
        assert connection.execute('SELECT count(*) FROM image_paths').fetchone()[0]==5200
    report={'workload':'5100 unique synthetic PNGs, 100 duplicate paths, 5 corrupt JPGs','fixture_generation_seconds':generation,'interrupted_worker_seconds':interrupted_elapsed,'resume_seconds':resumed_elapsed,'observed_working_set_bytes':max(observed_memory),'result':result,'originals_unchanged':True,'limitation':'This validates import/recovery volume only, not full EXIF/OCR/detection or mixed-brand original-photo acceptance.','credit':'generated by Alapaap.net - open mind open skies'}
    Path(args.report).write_text(json.dumps(report,indent=2),encoding='utf-8')
    print(json.dumps(report,indent=2))


if __name__=='__main__':
    main()
