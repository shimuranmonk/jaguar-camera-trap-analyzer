"""Assemble a one-folder offline preview without a system Python dependency."""
import argparse
import email
import hashlib
import json
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--destination',required=True)
    parser.add_argument('--python-zip',required=True)
    parser.add_argument('--ocr-models',required=True)
    parser.add_argument('--detector-models',required=True)
    parser.add_argument('--exiftool',required=True)
    args=parser.parse_args()
    source=Path(__file__).resolve().parents[1]
    destination=Path(args.destination).resolve()
    destination.mkdir(parents=True,exist_ok=False)
    runtime=destination/'runtime'
    runtime.mkdir()
    with zipfile.ZipFile(args.python_zip) as archive:
        archive.extractall(runtime)
    # The embedded interpreter searches only this explicit offline distribution.
    (runtime/'python313._pth').write_text('python313.zip\n.\nLib/site-packages\napp\nimport site\n',encoding='utf-8')
    packages=Path(sys.prefix)/'Lib/site-packages'
    print('Copying runtime packages',flush=True)
    shutil.copytree(packages,runtime/'Lib/site-packages',ignore=shutil.ignore_patterns('__pycache__'))
    shutil.copytree(source/'jaguar',runtime/'app/jaguar',ignore=shutil.ignore_patterns('__pycache__'))
    resources=destination/'resources'
    resources.mkdir()
    for name,path in [('ocr-models',args.ocr_models),('detector-models',args.detector_models),('exiftool',args.exiftool)]:
        shutil.copytree(path,resources/name,ignore=shutil.ignore_patterns('__pycache__','.cache'))
    inventory=[]
    for metadata in sorted(packages.glob('*.dist-info/METADATA')):
        message=email.message_from_string(metadata.read_text(encoding='utf-8',errors='replace'))
        inventory.append({'name':message.get('Name'),'version':message.get('Version'),'license':message.get('License-Expression') or message.get('License'),'home_page':message.get('Home-page'),'project_urls':message.get_all('Project-URL',[])})
    notices=destination/'notices'
    notices.mkdir()
    (notices/'dependency-inventory.json').write_text(json.dumps({'credit':'generated by Alapaap.net - open mind open skies','packages':inventory},indent=2),encoding='utf-8')
    shutil.copy2(source/'LICENSE',notices/'APPLICATION-LICENSE.txt')
    shutil.copytree(source/'docs',destination/'docs')
    (destination/'README.txt').write_text('The JAGUAR MVP 1 preview\n\nJAGUAR.exe launches the local desktop application. Python, CPU inference packages, and local models are included. Project files and original photographs remain separate. This preview still requires fresh-machine, GPU, larger original-data, and redistribution validation before release. Third-party license files remain in runtime/Lib/site-packages and the notices inventory.\n\ngenerated by Alapaap.net - open mind open skies\n',encoding='utf-8')
    build_root=destination.parent/'launcher-build'
    subprocess.run([sys.executable,'-m','PyInstaller','--noconfirm','--onedir','--windowed','--name','JAGUAR','--distpath',str(build_root/'dist'),'--workpath',str(build_root/'work'),'--specpath',str(build_root),str(source/'packaging/launcher.py')],check=True)
    for item in (build_root/'dist/JAGUAR').iterdir():
        if item.is_dir():
            shutil.copytree(item,destination/item.name)
        else:
            shutil.copy2(item,destination/item.name)
    hashes={}
    for path in [Path(args.python_zip),resources/'detector-models/checkpoints/MDV6-mit-yolov9-c.ckpt',resources/'ocr-models/det/inference.pdiparams',resources/'ocr-models/rec/inference.pdiparams']:
        with path.open('rb') as handle:
            hashes[path.name if path.name!='inference.pdiparams' else path.parent.name+'/'+path.name]=hashlib.file_digest(handle,'sha256').hexdigest()
    (notices/'asset-hashes.json').write_text(json.dumps(hashes,indent=2),encoding='utf-8')
    print('One-folder preview assembled: '+str(destination),flush=True)


if __name__=='__main__':
    main()
